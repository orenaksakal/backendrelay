/**
 * C.13. The event and payload paths end in a wildcard because an ISN contains
 * slashes (`0/328/48953748`); the dashboard percent-encodes them into one
 * segment, and both forms resolve here.
 */
function webhookHandlers(base: string) {
  const webhookPath = `${base}/dash/apps/:appId/webhooks/:webhookId`;
  return [
    http.get(`${base}/dash/apps/:appId/webhooks`, () =>
      HttpResponse.json({ webhooks: mockWebhooks }),
    ),
    http.post(`${base}/dash/apps/:appId/webhooks`, async ({ request }) => {
      const body = (await request.json()) as {
        url?: string;
        namespaces?: string[];
        actions?: Webhook['actions'];
      };
      return HttpResponse.json({
        webhook: {
          id: 'webhook-created',
          sink: { url: body.url ?? 'https://example.com/hooks/new' },
          namespaces: body.namespaces ?? [],
          actions: body.actions ?? ['create'],
          status: 'active',
          disabled_reason: null,
          created_at: '2026-10-27T10:00:00Z',
          updated_at: '2026-10-27T10:00:00Z',
        },
      });
    }),
    http.post(webhookPath, async ({ params, request }) => {
      const body = (await request.json()) as {
        url?: string;
        namespaces?: string[];
        actions?: Webhook['actions'];
      };
      const existing =
        mockWebhooks.find((webhook) => webhook.id === params['webhookId']) ??
        mockWebhooks[0];
      return HttpResponse.json({
        webhook: {
          ...existing,
          ...(body.url === undefined ? {} : { sink: { url: body.url } }),
          ...(body.namespaces === undefined
            ? {}
            : { namespaces: body.namespaces }),
          ...(body.actions === undefined ? {} : { actions: body.actions }),
          updated_at: '2026-10-27T10:05:00Z',
        },
      });
    }),
    http.delete(webhookPath, ({ params }) => {
      const existing =
        mockWebhooks.find((webhook) => webhook.id === params['webhookId']) ??
        mockWebhooks[0];
      return HttpResponse.json({ webhook: existing });
    }),
    http.post(`${webhookPath}/enable`, ({ params }) => {
      const existing =
        mockWebhooks.find((webhook) => webhook.id === params['webhookId']) ??
        mockWebhooks[0];
      return HttpResponse.json({
        webhook: { ...existing, status: 'active', disabled_reason: null },
      });
    }),
    http.post(`${webhookPath}/disable`, async ({ params, request }) => {
      const body = (await request.json()) as { reason?: string };
      const existing =
        mockWebhooks.find((webhook) => webhook.id === params['webhookId']) ??
        mockWebhooks[0];
      return HttpResponse.json({
        webhook: {
          ...existing,
          status: 'disabled',
          disabled_reason: body.reason ?? null,
        },
      });
    }),
    http.get(`${webhookPath}/events`, ({ request }) => {
      const after = new URL(request.url).searchParams.get('after');
      if (after === null) {
        return HttpResponse.json({
          events: mockWebhookEvents,
          pageInfo: {
            startCursor: 'cursor-0',
            endCursor: 'cursor-1',
            hasNextPage: true,
          },
        });
      }
      return HttpResponse.json({
        events: mockWebhookOlderEvents,
        pageInfo: {
          startCursor: 'cursor-2',
          endCursor: 'cursor-2',
          hasNextPage: false,
        },
      });
    }),
    http.get(`${webhookPath}/events/*`, ({ request }) => {
      const event = findMockEvent(trailingIsn(request, '/events/', 0));
      if (event === undefined) {
        return HttpResponse.json(
          { type: 'record-not-found', message: 'Webhook event not found' },
          { status: 404 },
        );
      }
      return HttpResponse.json({ event });
    }),
    http.post(`${webhookPath}/events/*`, ({ request }) => {
      const event = findMockEvent(trailingIsn(request, '/events/', 0));
      if (event === undefined) {
        return HttpResponse.json(
          { type: 'record-not-found', message: 'Webhook event not found' },
          { status: 404 },
        );
      }
      return HttpResponse.json({
        event: { ...event, status: 'pending', next_attempt_after: null },
      });
    }),
    http.get(`${base}/webhooks/payload/:appId/:webhookId/*`, ({ request }) =>
      HttpResponse.json(
        trailingIsn(request, '/webhooks/payload/', 2) === '0/301/11111111'
          ? mockMissingWebhookPayload
          : mockWebhookPayload,
      ),
    ),
  ];
}

function trailingIsn(request: Request, marker: string, skip = 2): string {
  const path = new URL(request.url).pathname;
  const rest = path.slice(path.indexOf(marker) + marker.length);
  return decodeURIComponent(rest.split('/').slice(skip).join('/'));
}

function findMockEvent(isn: string) {
  return [...mockWebhookEvents, ...mockWebhookOlderEvents].find(
    (event) => event.isn === isn,
  );
}

