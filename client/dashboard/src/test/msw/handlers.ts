function oauthAppForId(oauthAppId: unknown) {
  return (
    mockOauthApps.find((app) => app.id === String(oauthAppId)) ?? mockOauthApp
  );
}

function oauthClientForId(clientId: unknown): OauthAppClient {
  for (const app of mockOauthApps) {
    const client = (app.clients ?? []).find(
      (candidate) => candidate.clientId === String(clientId),
    );
    if (client !== undefined) return client;
  }
  return mockOauthClient;
}

